-- Durable cloud worker queue. Apply once with scripts/setup-cloud-agent.cjs.
CREATE TABLE IF NOT EXISTS "AgentPreference" (
 "userId" TEXT PRIMARY KEY REFERENCES "User"("id") ON DELETE CASCADE,
 "enabled" BOOLEAN NOT NULL DEFAULT FALSE,"consentedAt" TIMESTAMPTZ,
 "nextRunAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),"updatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS "AgentRun" (
 "id" TEXT PRIMARY KEY,"userId" TEXT NOT NULL REFERENCES "User"("id") ON DELETE CASCADE,
 "applicationId" TEXT NOT NULL REFERENCES "JobApplication"("id") ON DELETE CASCADE,
 "resumeId" TEXT NOT NULL,"url" TEXT NOT NULL,"state" TEXT NOT NULL DEFAULT 'QUEUED',
 "reason" TEXT NOT NULL DEFAULT '',"steps" INTEGER NOT NULL DEFAULT 0,"resumeUploaded" BOOLEAN NOT NULL DEFAULT FALSE,
 "leaseOwner" TEXT,"leaseUntil" TIMESTAMPTZ,"submitReservedAt" TIMESTAMPTZ,"confirmation" JSONB,
 "screen" TEXT,"screenVersion" INTEGER NOT NULL DEFAULT 0,"fields" JSONB NOT NULL DEFAULT '[]',
 "interactiveUntil" TIMESTAMPTZ,"handoffHash" TEXT,"handoffExpires" TIMESTAMPTZ,"handoffUsedAt" TIMESTAMPTZ,
 "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),"updatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS "AgentRun_one_application" ON "AgentRun"("applicationId")
 WHERE "state" IN ('QUEUED','RUNNING','WAITING_USER','SUBMITTING','UNKNOWN','CONFIRMED');
CREATE INDEX IF NOT EXISTS "AgentRun_queue" ON "AgentRun"("state","createdAt");
ALTER TABLE "AgentRun" ADD COLUMN IF NOT EXISTS "resumeUploaded" BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE "AgentRun" ADD COLUMN IF NOT EXISTS "retryCount" INTEGER NOT NULL DEFAULT 0;
ALTER TABLE "AgentRun" ADD COLUMN IF NOT EXISTS "nextAttemptAt" TIMESTAMPTZ NOT NULL DEFAULT NOW();
CREATE TABLE IF NOT EXISTS "AgentSession" (
 "userId" TEXT PRIMARY KEY REFERENCES "User"("id") ON DELETE CASCADE,
 "encrypted" TEXT NOT NULL,"updatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS "AgentCommand" (
 "id" TEXT PRIMARY KEY,"runId" TEXT NOT NULL REFERENCES "AgentRun"("id") ON DELETE CASCADE,
 "encrypted" TEXT NOT NULL,"screenVersion" INTEGER NOT NULL,"expiresAt" TIMESTAMPTZ NOT NULL,
 "createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS "AgentNotice" (
 "id" TEXT PRIMARY KEY,"runId" TEXT NOT NULL REFERENCES "AgentRun"("id") ON DELETE CASCADE,
 "encrypted" TEXT NOT NULL,"state" TEXT NOT NULL DEFAULT 'PENDING',"attempts" INTEGER NOT NULL DEFAULT 0,
 "expiresAt" TIMESTAMPTZ NOT NULL,"createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(),"sentAt" TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS "AgentEvent" (
 "id" TEXT PRIMARY KEY,"runId" TEXT NOT NULL REFERENCES "AgentRun"("id") ON DELETE CASCADE,
 "kind" TEXT NOT NULL,"message" TEXT NOT NULL,"createdAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS "AgentHeartbeat" (
 "id" TEXT PRIMARY KEY,"updatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE "AgentHeartbeat" ADD COLUMN IF NOT EXISTS "modelReady" BOOLEAN NOT NULL DEFAULT FALSE;
CREATE TABLE IF NOT EXISTS "AgentUserLease" (
 "userId" TEXT PRIMARY KEY REFERENCES "User"("id") ON DELETE CASCADE,
 "runId" TEXT NOT NULL,"owner" TEXT NOT NULL,"expiresAt" TIMESTAMPTZ NOT NULL
);
